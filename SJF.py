# ---------------------------------------------------------
# دالة لحساب زمن انتظار العملاء في البنك باستخدام Greedy (SJF)
# الفكرة: نخدم العملاء اللي عندهم أقل وقت خدمة الأول
# ---------------------------------------------------------

def greedy_bank_waiting(customers):
    """
    customers: قائمة فيها عناصر بشكل (اسم العميل، زمن خدمته)
    مثال:
        [("Customer 1", 5), ("Customer 2", 1)]
    """

    # ---------------------------------------------------------
    # 1) Greedy Step:
    # نرتّب العملاء حسب زمن الخدمة تصاعدياً
    # lambda x: x[1] يعني رتب حسب العنصر الثاني (وقت الخدمة)
    # ---------------------------------------------------------
    customers_sorted = sorted(customers, key=lambda x: x[1])

    # دي هتبقى Dictionary نخزن فيها كل عميل وزمن انتظاره
    waiting_times = {}

    # ده الوقت اللي وصلنا له بعد خدمة العملاء اللي قبله
    current_time = 0

    # ---------------------------------------------------------
    # 2) نحسب زمن انتظار كل عميل بالترتيب بعد الفرز
    # العميل اللي ييجي أول واحد (أقل وقت خدمة) → ينتظر 0
    # العميل اللي بعده → ينتظر وقت خدمة العميل اللي قبله
    # ---------------------------------------------------------
    for name, service_time in customers_sorted:
        
        # زمن انتظار العميل = الزمن الحالي قبل خدمته
        waiting_times[name] = current_time
        
        # بعد ما العميل الحالي يتخدم → الوقت يزيد بزمن خدمته
        current_time += service_time

    # ---------------------------------------------------------
    # 3) إجمالي زمن الانتظار = مجموع كل أزمنة الانتظار
    # ---------------------------------------------------------
    total_wait = sum(waiting_times.values())

    # نرجّع:
    # - زمن انتظار كل عميل في Dictionary
    # - إجمالي الزمن الكلي
    return waiting_times, total_wait


# ---------------------------------------------------------
# مثال للتجربة
# ---------------------------------------------------------
customers = [
    ("Customer 1", 5),
    ("Customer 2", 1),
    ("Customer 3", 8),
    ("Customer 4", 3),
]

# استدعاء الدالة
waiting, total = greedy_bank_waiting(customers)

# طباعة النتائج
print(":waiting for every customer")
for customer, w in waiting.items():
    print(f"{customer} wait {w} minute")

print("\n:total waiting time", total)